CREATE TABLE IF NOT EXISTS profile_info (
    id BIGINT PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    initials VARCHAR(12) NOT NULL,
    avatar_url VARCHAR(500),
    handle VARCHAR(100) NOT NULL,
    role_vi VARCHAR(200) NOT NULL,
    role_en VARCHAR(200) NOT NULL,
    availability_vi VARCHAR(255) NOT NULL,
    availability_en VARCHAR(255) NOT NULL,
    location_vi VARCHAR(150) NOT NULL,
    location_en VARCHAR(150) NOT NULL,
    timezone VARCHAR(32) NOT NULL,
    email VARCHAR(200) NOT NULL DEFAULT '',
    phone VARCHAR(60),
    cv_pdf_url VARCHAR(500),
    headline_vi TEXT NOT NULL,
    headline_en TEXT NOT NULL,
    bio_vi TEXT NOT NULL,
    bio_en TEXT NOT NULL,
    current_focus_vi TEXT NOT NULL,
    current_focus_en TEXT NOT NULL,
    metrics_json TEXT NOT NULL DEFAULT '[]',
    socials_json TEXT NOT NULL DEFAULT '[]',
    languages_vi_json TEXT NOT NULL DEFAULT '[]',
    languages_en_json TEXT NOT NULL DEFAULT '[]',
    is_draft BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS skill_groups (
    id VARCHAR(80) PRIMARY KEY,
    title_vi VARCHAR(150) NOT NULL,
    title_en VARCHAR(150) NOT NULL,
    description_vi TEXT NOT NULL,
    description_en TEXT NOT NULL,
    accent VARCHAR(32) NOT NULL DEFAULT 'emerald',
    items_json TEXT NOT NULL DEFAULT '[]',
    sort_order INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS experiences (
    id VARCHAR(80) PRIMARY KEY,
    company VARCHAR(150) NOT NULL,
    role_vi VARCHAR(150) NOT NULL,
    role_en VARCHAR(150) NOT NULL,
    period_vi VARCHAR(100) NOT NULL,
    period_en VARCHAR(100) NOT NULL,
    location_vi VARCHAR(150) NOT NULL,
    location_en VARCHAR(150) NOT NULL,
    type_vi VARCHAR(80) NOT NULL,
    type_en VARCHAR(80) NOT NULL,
    summary_vi TEXT NOT NULL,
    summary_en TEXT NOT NULL,
    achievements_vi_json TEXT NOT NULL DEFAULT '[]',
    achievements_en_json TEXT NOT NULL DEFAULT '[]',
    stack_json TEXT NOT NULL DEFAULT '[]',
    sort_order INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS education_items (
    id VARCHAR(80) PRIMARY KEY,
    school VARCHAR(200) NOT NULL,
    degree_vi VARCHAR(200) NOT NULL,
    degree_en VARCHAR(200) NOT NULL,
    period_vi VARCHAR(100) NOT NULL,
    period_en VARCHAR(100) NOT NULL,
    gpa VARCHAR(40),
    details_vi TEXT NOT NULL,
    details_en TEXT NOT NULL,
    sort_order INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS projects (
    id VARCHAR(80) PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    category VARCHAR(32) NOT NULL DEFAULT 'fullstack',
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    project_year VARCHAR(16) NOT NULL,
    tagline_vi TEXT NOT NULL,
    tagline_en TEXT NOT NULL,
    description_vi TEXT NOT NULL,
    description_en TEXT NOT NULL,
    highlights_vi_json TEXT NOT NULL DEFAULT '[]',
    highlights_en_json TEXT NOT NULL DEFAULT '[]',
    stack_json TEXT NOT NULL DEFAULT '[]',
    live_url VARCHAR(500),
    repo_url VARCHAR(500),
    secondary_repo_url VARCHAR(500),
    sort_order INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(200) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
