import type { ContentNode } from '@/types/node'

function skillRow(
  id: string,
  parentId: string,
  sortOrder: number,
  labelVi: string,
  labelEn: string,
  items: string[],
): ContentNode {
  return {
    id,
    parentId,
    tag: 'card',
    sortOrder,
    attrs: {
      bgColor: 'transparent',
      borderColor: 'transparent',
      rounded: 'none',
      padding: 'sm',
      stackDirection: 'row',
      stackWrap: true,
      gap: 4,
    },
    contentVi: '',
    contentEn: '',
    children: [
      {
        id: `${id}-label`,
        parentId: id,
        tag: 'text',
        sortOrder: 0,
        attrs: { fontSize: 'xs', textColor: '#27272a', width: '9rem' },
        contentVi: `<p><strong>${labelVi}</strong></p>`,
        contentEn: `<p><strong>${labelEn}</strong></p>`,
        children: [],
      },
      {
        id: `${id}-badges`,
        parentId: id,
        tag: 'badge-group',
        sortOrder: 1,
        attrs: { gap: 2 },
        contentVi: '',
        contentEn: '',
        children: items.map((item, idx) => ({
          id: `${id}-b-${idx}`,
          parentId: `${id}-badges`,
          tag: 'badge',
          sortOrder: idx,
          attrs: {
            mono: true,
            bgColor: '#fafafa',
            textColor: '#3f3f46',
            borderColor: '#e4e4e7',
          },
          contentVi: item,
          contentEn: item,
          children: [],
        })),
      },
    ],
  }
}

